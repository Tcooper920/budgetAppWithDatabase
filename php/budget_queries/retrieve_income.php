<?php

require('../../../../connect_budget_database.php');

$userid = $_SESSION['user_id'];

# Get last saved income amount using a parameterized query...
// Prepare statement...
$query_to_get_income = $budget_database->prepare("SELECT total_income FROM user_income WHERE income_id=(SELECT max(income_id) FROM user_income WHERE user_id=?)");
// Bind parameters...
$query_to_get_income->bind_param("i", $userid);
// Execute statement...
$query_to_get_income->execute();
// Get result (income)...
$get_income = $query_to_get_income->get_result();
// Check result...
$last_saved_income = mysqli_fetch_array($get_income);

# If a previous income wasn't saved, make it "0", else display the saved income amount...
$current_income = is_null($last_saved_income) ? 0 : "$last_saved_income[0]";